/****** Object:  UserDefinedTableType [UDT].[DocSubCategory] ******/
CREATE TYPE [UDT].[DocSubCategory] AS TABLE(
	[ROW_KEY]		INT				NOT NULL
,	[NAME]			VARCHAR(80)		NULL
,	[OPTION_TYPE]	VARCHAR(80)		NULL
)
GO

/****** Object:  UserDefinedTableType [UDT].[DocOption] ******/
CREATE TYPE [UDT].[DocOption] AS TABLE(
	[ROW_KEY]		INT				NULL	/*NULL = OPTION OF THE MAIN CATEGORY, ELSE MATCHES [UDT].[DocSubCategory].[ROW_KEY]*/
,	[LABEL]			VARCHAR(MAX)	NULL
)
GO

SET ANSI_NULLS ON
GO
SET QUOTED_IDENTIFIER ON
GO
/****** Object:  StoredProcedure [DOC].[NSP_DocumentSetup] ******/
CREATE OR ALTER PROCEDURE [DOC].[NSP_DocumentSetup]
	@FLAG				VARCHAR(120)	= ''

	/*MAIN CATEGORY PARAMS*/
,	@MAIN_ID			INT				= NULL
,	@NAME				VARCHAR(80)		= ''
,	@IS_NO_SUBCATEGORY	BIT				= 0
,	@OPTION_TYPE		VARCHAR(80)		= ''

	/*SUB CATEGORY PARAMS*/
,	@SUB_ID				INT				= NULL
,	@SUB_CATEGORY		[UDT].[DocSubCategory]	READONLY

	/*OPTION PARAMS*/
,	@OPTION_ID			INT				= NULL
,	@LABEL				VARCHAR(MAX)	= NULL	/*[DOC].[Options].[LABEL] IS VARCHAR(MAX), SO @NAME CANNOT CARRY IT*/
,	@OPTIONS			[UDT].[DocOption]		READONLY

	/*OTHER PARAMS*/
,	@CREATED_BY			BIGINT			= NULL
,	@SEARCH				VARCHAR(120)	= ''
,	@PageNumber			INT				= 1
,	@PageSize			INT				= 10

AS
BEGIN
	SET NOCOUNT ON;

	DECLARE	@Offset INT = (@PageNumber - 1) * @PageSize;

	/*MAPS THE CLIENT SIDE ROW KEY TO THE IDENTITY GENERATED BY [DOC].[SubCategory]*/
	DECLARE @xSubMap AS TABLE (
		[ROW_KEY]	INT
	,	[SUB_ID]	INT
	)

	DECLARE @xMainId INT;

	/*THE PARENT OF THE OPTION BEING SOFT DELETED - EXACTLY ONE OF THEM IS SET*/
	DECLARE	@xOptionMainId	INT
	,		@xOptionSubId	INT;

	-- EXEC [DOC].[NSP_DocumentSetup] 'GET CATEGORIES', @PageNumber = 1, @PageSize = 10

	-- =================================
	-- CREATE CATEGORY
	-- =================================
	IF @FLAG = 'CREATE CATEGORY'
	BEGIN
		IF LTRIM(RTRIM(ISNULL(@NAME, ''))) = ''
		BEGIN
			RAISERROR('Category name is required.', 16, 1);
			RETURN;
		END

		/*ONLY ACTIVE ROWS RESERVE A NAME - A SOFT DELETED ONE FREES IT UP AGAIN*/
		IF EXISTS (
			SELECT	1
			FROM	[DOC].[MainCategory]
			WHERE	[NAME] = LTRIM(RTRIM(@NAME))
			AND		[IS_ACTIVE] = 1
		)
		BEGIN
			RAISERROR('Category already exists.', 16, 1);
			RETURN;
		END

		BEGIN TRY
			BEGIN TRANSACTION;

				INSERT INTO [DOC].[MainCategory] (
						[NAME]
					,	[IS_NO_SUBCATEGORY]
					,	[OPTION_TYPE]
					,	[CREATED_DATE]
					,	[CREATED_BY]
					,	[IS_ACTIVE]
				)
				VALUES (
						LTRIM(RTRIM(@NAME))
					,	@IS_NO_SUBCATEGORY
					,	CASE WHEN @IS_NO_SUBCATEGORY = 1 THEN @OPTION_TYPE ELSE NULL END
					,	GETDATE()
					,	@CREATED_BY
					,	1
				)

				SET @MAIN_ID = CAST(SCOPE_IDENTITY() AS INT);

				IF @IS_NO_SUBCATEGORY = 1
				BEGIN
					/*THE CATEGORY ANSWERS DIRECTLY, SO THE OPTIONS BELONG TO THE MAIN CATEGORY*/
					INSERT INTO [DOC].[Options] (
							[LABEL]
						,	[MAIN_CATEGORY_ID]
						,	[SUB_CATEGORY_ID]
						,	[IS_ACTIVE]
					)
					SELECT		opt.[LABEL]
							,	@MAIN_ID
							,	NULL
							,	1
					FROM		@OPTIONS opt
					WHERE		opt.[ROW_KEY] IS NULL
					AND			LTRIM(RTRIM(ISNULL(opt.[LABEL], ''))) <> ''
				END
				ELSE
				BEGIN
					/*MERGE IS USED ONLY TO CAPTURE source.[ROW_KEY] BESIDE THE NEW IDENTITY*/
					MERGE	[DOC].[SubCategory]	target
					USING	@SUB_CATEGORY		source
					ON		1 = 0
					WHEN NOT MATCHED THEN
						INSERT (
								[NAME]
							,	[MAIN_ID]
							,	[OPTION_TYPE]
							,	[CREATED_DATE]
							,	[CREATED_BY]
							,	[IS_ACTIVE]
						)
						VALUES (
								LTRIM(RTRIM(source.[NAME]))
							,	@MAIN_ID
							,	source.[OPTION_TYPE]
							,	GETDATE()
							,	@CREATED_BY
							,	1
						)
					OUTPUT	source.[ROW_KEY], inserted.[ID]
					INTO	@xSubMap ([ROW_KEY], [SUB_ID]);

					INSERT INTO [DOC].[Options] (
							[LABEL]
						,	[MAIN_CATEGORY_ID]
						,	[SUB_CATEGORY_ID]
						,	[IS_ACTIVE]
					)
					SELECT		opt.[LABEL]
							,	NULL
							,	map.[SUB_ID]
							,	1
					FROM		@OPTIONS	opt
					INNER JOIN	@xSubMap	map
					ON			map.[ROW_KEY] = opt.[ROW_KEY]
					WHERE		LTRIM(RTRIM(ISNULL(opt.[LABEL], ''))) <> ''
				END

			COMMIT TRANSACTION;
		END TRY
		BEGIN CATCH
			IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
			THROW;
		END CATCH

		SELECT @MAIN_ID [ID];
	END

	-- =================================
	-- UPDATE CATEGORY
	-- =================================
	IF @FLAG = 'UPDATE CATEGORY'
	BEGIN
		IF NOT EXISTS (SELECT 1 FROM [DOC].[MainCategory] WHERE [ID] = @MAIN_ID AND [IS_ACTIVE] = 1)
		BEGIN
			RAISERROR('Category does not exist.', 16, 1);
			RETURN;
		END

		IF LTRIM(RTRIM(ISNULL(@NAME, ''))) = ''
		BEGIN
			RAISERROR('Category name is required.', 16, 1);
			RETURN;
		END

		IF EXISTS (
			SELECT	1
			FROM	[DOC].[MainCategory]
			WHERE	[NAME] = LTRIM(RTRIM(@NAME))
			AND		[ID] <> @MAIN_ID
			AND		[IS_ACTIVE] = 1
		)
		BEGIN
			RAISERROR('Category already exists.', 16, 1);
			RETURN;
		END

		BEGIN TRY
			BEGIN TRANSACTION;

				UPDATE		[DOC].[MainCategory]
				SET			[NAME]				= LTRIM(RTRIM(@NAME))
						,	[IS_NO_SUBCATEGORY]	= @IS_NO_SUBCATEGORY
						,	[OPTION_TYPE]		= CASE WHEN @IS_NO_SUBCATEGORY = 1 THEN @OPTION_TYPE ELSE NULL END
				WHERE		[ID] = @MAIN_ID

				/*
					CHILD ROWS ARE REBUILT FROM THE PAYLOAD. ONLY THE ACTIVE ONES ARE
					CLEARED - SOFT DELETED SUB CATEGORIES AND OPTIONS STAY AS HISTORY.
				*/
				DELETE		opt
				FROM		[DOC].[Options]		opt
				LEFT JOIN	[DOC].[SubCategory]	sub
				ON			sub.[ID] = opt.[SUB_CATEGORY_ID]
				WHERE		opt.[IS_ACTIVE] = 1
				AND			(
								opt.[MAIN_CATEGORY_ID] = @MAIN_ID
							OR	(sub.[MAIN_ID] = @MAIN_ID AND sub.[IS_ACTIVE] = 1)
							)

				DELETE FROM	[DOC].[SubCategory]
				WHERE		[MAIN_ID] = @MAIN_ID
				AND			[IS_ACTIVE] = 1

				IF @IS_NO_SUBCATEGORY = 1
				BEGIN
					INSERT INTO [DOC].[Options] (
							[LABEL]
						,	[MAIN_CATEGORY_ID]
						,	[SUB_CATEGORY_ID]
						,	[IS_ACTIVE]
					)
					SELECT		opt.[LABEL]
							,	@MAIN_ID
							,	NULL
							,	1
					FROM		@OPTIONS opt
					WHERE		opt.[ROW_KEY] IS NULL
					AND			LTRIM(RTRIM(ISNULL(opt.[LABEL], ''))) <> ''
				END
				ELSE
				BEGIN
					MERGE	[DOC].[SubCategory]	target
					USING	@SUB_CATEGORY		source
					ON		1 = 0
					WHEN NOT MATCHED THEN
						INSERT (
								[NAME]
							,	[MAIN_ID]
							,	[OPTION_TYPE]
							,	[CREATED_DATE]
							,	[CREATED_BY]
							,	[IS_ACTIVE]
						)
						VALUES (
								LTRIM(RTRIM(source.[NAME]))
							,	@MAIN_ID
							,	source.[OPTION_TYPE]
							,	GETDATE()
							,	@CREATED_BY
							,	1
						)
					OUTPUT	source.[ROW_KEY], inserted.[ID]
					INTO	@xSubMap ([ROW_KEY], [SUB_ID]);

					INSERT INTO [DOC].[Options] (
							[LABEL]
						,	[MAIN_CATEGORY_ID]
						,	[SUB_CATEGORY_ID]
						,	[IS_ACTIVE]
					)
					SELECT		opt.[LABEL]
							,	NULL
							,	map.[SUB_ID]
							,	1
					FROM		@OPTIONS	opt
					INNER JOIN	@xSubMap	map
					ON			map.[ROW_KEY] = opt.[ROW_KEY]
					WHERE		LTRIM(RTRIM(ISNULL(opt.[LABEL], ''))) <> ''
				END

			COMMIT TRANSACTION;
		END TRY
		BEGIN CATCH
			IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
			THROW;
		END CATCH

		SELECT @MAIN_ID [ID];
	END

	-- =================================
	-- GET CATEGORIES (PAGINATED)
	-- =================================
	IF @FLAG = 'GET CATEGORIES'
	BEGIN
		WITH PaginatedResults AS (
			SELECT		mcat.[ID]
					,	mcat.[NAME]
					,	mcat.[IS_NO_SUBCATEGORY]
					,	mcat.[OPTION_TYPE]
					,	mcat.[CREATED_DATE]
					,	mcat.[CREATED_BY]
					,	usr.[USERNAME] [CREATED_BY_NAME]
					,	mcat.[IS_ACTIVE]
					,	(
							SELECT	COUNT(1)
							FROM	[DOC].[SubCategory] sub
							WHERE	sub.[MAIN_ID] = mcat.[ID]
							AND		sub.[IS_ACTIVE] = 1
						) [SUB_CATEGORY_COUNT]
						/*ONLY THE CATEGORY'S OWN OPTIONS - A CATEGORY WITH SUB CATEGORIES HAS NONE*/
					,	(
							SELECT	COUNT(1)
							FROM	[DOC].[Options] opt
							WHERE	opt.[MAIN_CATEGORY_ID] = mcat.[ID]
							AND		opt.[IS_ACTIVE] = 1
						) [OPTION_COUNT]
					,	ROW_NUMBER() OVER (ORDER BY mcat.[NAME] ASC) AS RowNum
					,	COUNT(*) OVER() AS TotalCount
			FROM		[DOC].[MainCategory] mcat
			LEFT JOIN	[dbo].[USERS] usr
			ON			usr.[ID] = mcat.[CREATED_BY]
			WHERE		mcat.[IS_ACTIVE] = 1
			AND			(@SEARCH = '' OR mcat.[NAME] LIKE '%' + @SEARCH + '%')
		)
		SELECT		[ID]
				,	[NAME]
				,	[IS_NO_SUBCATEGORY]
				,	[OPTION_TYPE]
				,	[CREATED_DATE]
				,	[CREATED_BY]
				,	[CREATED_BY_NAME]
				,	[IS_ACTIVE]
				,	[SUB_CATEGORY_COUNT]
				,	[OPTION_COUNT]
				,	TotalCount
					-- Pagination metadata
				,	@PageNumber AS CurrentPage
				,	@PageSize AS PageSize
				,	CEILING(CAST(TotalCount AS FLOAT) / @PageSize) AS TotalPages
				,	CASE
						WHEN @PageNumber < CEILING(CAST(TotalCount AS FLOAT) / @PageSize) THEN 1
						ELSE 0
					END AS HasNextPage
				,	CASE
						WHEN @PageNumber > 1 THEN 1
						ELSE 0
					END AS HasPreviousPage
		FROM		PaginatedResults
		WHERE		RowNum BETWEEN @Offset + 1 AND @Offset + @PageSize
		ORDER BY	[NAME] ASC;
	END

	-- =================================
	-- GET CATEGORY BY ID (3 RESULT SETS)
	-- =================================
	IF @FLAG = 'GET CATEGORY BY ID'
	BEGIN
		/*1 - MAIN CATEGORY*/
		SELECT		mcat.[ID]
				,	mcat.[NAME]
				,	mcat.[IS_NO_SUBCATEGORY]
				,	mcat.[OPTION_TYPE]
				,	mcat.[CREATED_DATE]
				,	mcat.[CREATED_BY]
				,	usr.[USERNAME] [CREATED_BY_NAME]
				,	mcat.[IS_ACTIVE]
		FROM		[DOC].[MainCategory] mcat
		LEFT JOIN	[dbo].[USERS] usr
		ON			usr.[ID] = mcat.[CREATED_BY]
		WHERE		mcat.[ID] = @MAIN_ID
		AND			mcat.[IS_ACTIVE] = 1

		/*2 - SUB CATEGORIES*/
		SELECT		sub.[ID]
				,	sub.[NAME]
				,	sub.[MAIN_ID]
				,	sub.[OPTION_TYPE]
				,	sub.[CREATED_DATE]
				,	sub.[CREATED_BY]
				,	usr.[USERNAME] [CREATED_BY_NAME]
				,	sub.[IS_ACTIVE]
		FROM		[DOC].[SubCategory] sub
		LEFT JOIN	[dbo].[USERS] usr
		ON			usr.[ID] = sub.[CREATED_BY]
		WHERE		sub.[MAIN_ID] = @MAIN_ID
		AND			sub.[IS_ACTIVE] = 1
		ORDER BY	sub.[ID] ASC

		/*3 - OPTIONS OF THE MAIN CATEGORY AND OF EVERY ACTIVE SUB CATEGORY*/
		SELECT		opt.[ID]
				,	opt.[LABEL]
				,	opt.[MAIN_CATEGORY_ID]
				,	opt.[SUB_CATEGORY_ID]
				,	opt.[IS_ACTIVE]
		FROM		[DOC].[Options]		opt
		LEFT JOIN	[DOC].[SubCategory]	sub
		ON			sub.[ID] = opt.[SUB_CATEGORY_ID]
		WHERE		opt.[IS_ACTIVE] = 1
		AND			(
						opt.[MAIN_CATEGORY_ID] = @MAIN_ID
					OR	(sub.[MAIN_ID] = @MAIN_ID AND sub.[IS_ACTIVE] = 1)
					)
		ORDER BY	opt.[ID] ASC
	END

	-- =================================
	-- CREATE SUB CATEGORY
	-- =================================
	IF @FLAG = 'CREATE SUB CATEGORY'
	BEGIN
		/*@NAME AND @OPTION_TYPE CARRY THE SUB CATEGORY HERE, NOT THE MAIN ONE*/
		IF NOT EXISTS (SELECT 1 FROM [DOC].[MainCategory] WHERE [ID] = @MAIN_ID AND [IS_ACTIVE] = 1)
		BEGIN
			RAISERROR('Category does not exist.', 16, 1);
			RETURN;
		END

		/*
			CONVERTING A NO-SUBCATEGORY CATEGORY WOULD DISCARD ITS OWN TYPE AND
			OPTIONS, SO THAT HAS TO GO THROUGH 'UPDATE CATEGORY' DELIBERATELY.
		*/
		IF EXISTS (SELECT 1 FROM [DOC].[MainCategory] WHERE [ID] = @MAIN_ID AND [IS_NO_SUBCATEGORY] = 1)
		BEGIN
			RAISERROR('This category is flagged as having no sub-category. Edit the category first.', 16, 1);
			RETURN;
		END

		IF LTRIM(RTRIM(ISNULL(@NAME, ''))) = ''
		BEGIN
			RAISERROR('Sub-category name is required.', 16, 1);
			RETURN;
		END

		IF EXISTS (
			SELECT	1
			FROM	[DOC].[SubCategory]
			WHERE	[MAIN_ID] = @MAIN_ID
			AND		[NAME] = LTRIM(RTRIM(@NAME))
			AND		[IS_ACTIVE] = 1
		)
		BEGIN
			RAISERROR('Sub-category already exists.', 16, 1);
			RETURN;
		END

		BEGIN TRY
			BEGIN TRANSACTION;

				INSERT INTO [DOC].[SubCategory] (
						[NAME]
					,	[MAIN_ID]
					,	[OPTION_TYPE]
					,	[CREATED_DATE]
					,	[CREATED_BY]
					,	[IS_ACTIVE]
				)
				VALUES (
						LTRIM(RTRIM(@NAME))
					,	@MAIN_ID
					,	@OPTION_TYPE
					,	GETDATE()
					,	@CREATED_BY
					,	1
				)

				SET @SUB_ID = CAST(SCOPE_IDENTITY() AS INT);

				/*ONE SUB CATEGORY AT A TIME, SO EVERY OPTION IN THE PAYLOAD IS ITS OWN*/
				INSERT INTO [DOC].[Options] (
						[LABEL]
					,	[MAIN_CATEGORY_ID]
					,	[SUB_CATEGORY_ID]
					,	[IS_ACTIVE]
				)
				SELECT		opt.[LABEL]
						,	NULL
						,	@SUB_ID
						,	1
				FROM		@OPTIONS opt
				WHERE		LTRIM(RTRIM(ISNULL(opt.[LABEL], ''))) <> ''

			COMMIT TRANSACTION;
		END TRY
		BEGIN CATCH
			IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
			THROW;
		END CATCH

		SELECT @SUB_ID [ID];
	END

	-- =================================
	-- GET SUB CATEGORIES
	-- =================================
	IF @FLAG = 'GET SUB CATEGORIES'
	BEGIN
		/*1 - SUB CATEGORIES*/
		SELECT		sub.[ID]
				,	sub.[NAME]
				,	sub.[MAIN_ID]
				,	sub.[OPTION_TYPE]
				,	sub.[CREATED_DATE]
				,	sub.[CREATED_BY]
				,	usr.[USERNAME] [CREATED_BY_NAME]
				,	sub.[IS_ACTIVE]
		FROM		[DOC].[SubCategory] sub
		LEFT JOIN	[dbo].[USERS] usr
		ON			usr.[ID] = sub.[CREATED_BY]
		WHERE		sub.[MAIN_ID] = @MAIN_ID
		AND			sub.[IS_ACTIVE] = 1
		ORDER BY	sub.[ID] ASC

		/*2 - THEIR OPTIONS, SO THE CALLER CAN SHOW THEM WITHOUT A SECOND ROUND TRIP*/
		SELECT		opt.[ID]
				,	opt.[LABEL]
				,	opt.[MAIN_CATEGORY_ID]
				,	opt.[SUB_CATEGORY_ID]
				,	opt.[IS_ACTIVE]
		FROM		[DOC].[Options]		opt
		INNER JOIN	[DOC].[SubCategory]	sub
		ON			sub.[ID] = opt.[SUB_CATEGORY_ID]
		WHERE		sub.[MAIN_ID] = @MAIN_ID
		AND			sub.[IS_ACTIVE] = 1
		AND			opt.[IS_ACTIVE] = 1
		ORDER BY	opt.[ID] ASC
	END

	-- =================================
	-- GET OPTIONS
	-- =================================
	IF @FLAG = 'GET OPTIONS'
	BEGIN
		/*OPTIONS OF A SOFT DELETED SUB CATEGORY ARE HIDDEN ALONG WITH IT*/
		SELECT		opt.[ID]
				,	opt.[LABEL]
				,	opt.[MAIN_CATEGORY_ID]
				,	opt.[SUB_CATEGORY_ID]
				,	opt.[IS_ACTIVE]
		FROM		[DOC].[Options]		opt
		LEFT JOIN	[DOC].[SubCategory]	sub
		ON			sub.[ID] = opt.[SUB_CATEGORY_ID]
		WHERE		opt.[IS_ACTIVE] = 1
		AND			(@MAIN_ID IS NULL OR opt.[MAIN_CATEGORY_ID] = @MAIN_ID)
		AND			(@SUB_ID  IS NULL OR opt.[SUB_CATEGORY_ID]  = @SUB_ID)
		AND			(opt.[SUB_CATEGORY_ID] IS NULL OR sub.[IS_ACTIVE] = 1)
		ORDER BY	opt.[ID] ASC
	END

	-- =================================
	-- DELETE SUB CATEGORY
	-- =================================
	IF @FLAG = 'DELETE SUB CATEGORY'
	BEGIN
		SET @xMainId = (
			SELECT	[MAIN_ID]
			FROM	[DOC].[SubCategory]
			WHERE	[ID] = @SUB_ID
			AND		[IS_ACTIVE] = 1
		);

		IF @xMainId IS NULL
		BEGIN
			RAISERROR('Sub-category does not exist.', 16, 1);
			RETURN;
		END

		/*
			THE PARENT IS FLAGGED AS HAVING SUB CATEGORIES, SO IT CANNOT BE LEFT
			WITH NONE - THE SAME RULE THE CREATE FORM ENFORCES.
		*/
		IF (
			SELECT	COUNT(1)
			FROM	[DOC].[SubCategory]
			WHERE	[MAIN_ID] = @xMainId
			AND		[IS_ACTIVE] = 1
		) <= 1
		BEGIN
			RAISERROR('Cannot remove the last sub-category. Edit the category instead.', 16, 1);
			RETURN;
		END

		/*
			SOFT DELETE. THE OPTIONS ARE LEFT ALONE - THEY ARE ONLY REACHABLE
			THROUGH THE SUB CATEGORY, WHICH IS NOW HIDDEN.
		*/
		UPDATE		[DOC].[SubCategory]
		SET			[IS_ACTIVE] = 0
		WHERE		[ID] = @SUB_ID
		AND			[IS_ACTIVE] = 1
	END

	-- =================================
	-- CREATE OPTION
	-- =================================
	IF @FLAG = 'CREATE OPTION'
	BEGIN
		IF LTRIM(RTRIM(ISNULL(@LABEL, ''))) = ''
		BEGIN
			RAISERROR('Option is required.', 16, 1);
			RETURN;
		END

		/*AN OPTION HANGS OFF EXACTLY ONE PARENT, NEVER BOTH AND NEVER NEITHER*/
		IF (@MAIN_ID IS NULL AND @SUB_ID IS NULL)
		OR (@MAIN_ID IS NOT NULL AND @SUB_ID IS NOT NULL)
		BEGIN
			RAISERROR('An option belongs to either a category or a sub-category.', 16, 1);
			RETURN;
		END

		IF @MAIN_ID IS NOT NULL
		BEGIN
			IF NOT EXISTS (SELECT 1 FROM [DOC].[MainCategory] WHERE [ID] = @MAIN_ID AND [IS_ACTIVE] = 1)
			BEGIN
				RAISERROR('Category does not exist.', 16, 1);
				RETURN;
			END

			/*A CATEGORY WITH SUB CATEGORIES ANSWERS THROUGH THEM, SO IT OWNS NO OPTION*/
			IF EXISTS (
				SELECT	1
				FROM	[DOC].[MainCategory]
				WHERE	[ID] = @MAIN_ID
				AND		(ISNULL([IS_NO_SUBCATEGORY], 0) = 0 OR ISNULL([OPTION_TYPE], '') <> 'string')
			)
			BEGIN
				RAISERROR('Only a category with no sub-category and a string answer type can have options.', 16, 1);
				RETURN;
			END
		END
		ELSE
		BEGIN
			IF NOT EXISTS (SELECT 1 FROM [DOC].[SubCategory] WHERE [ID] = @SUB_ID AND [IS_ACTIVE] = 1)
			BEGIN
				RAISERROR('Sub-category does not exist.', 16, 1);
				RETURN;
			END

			IF EXISTS (
				SELECT	1
				FROM	[DOC].[SubCategory]
				WHERE	[ID] = @SUB_ID
				AND		ISNULL([OPTION_TYPE], '') <> 'string'
			)
			BEGIN
				RAISERROR('Only a sub-category with a string answer type can have options.', 16, 1);
				RETURN;
			END
		END

		/*ONLY ACTIVE ROWS RESERVE A LABEL - A SOFT DELETED ONE FREES IT UP AGAIN*/
		IF EXISTS (
			SELECT	1
			FROM	[DOC].[Options]
			WHERE	[LABEL] = LTRIM(RTRIM(@LABEL))
			AND		[IS_ACTIVE] = 1
			AND		(
						(@MAIN_ID IS NOT NULL AND [MAIN_CATEGORY_ID] = @MAIN_ID)
					OR	(@SUB_ID  IS NOT NULL AND [SUB_CATEGORY_ID]  = @SUB_ID)
					)
		)
		BEGIN
			RAISERROR('Option already exists.', 16, 1);
			RETURN;
		END

		INSERT INTO [DOC].[Options] (
				[LABEL]
			,	[MAIN_CATEGORY_ID]
			,	[SUB_CATEGORY_ID]
			,	[IS_ACTIVE]
		)
		VALUES (
				LTRIM(RTRIM(@LABEL))
			,	@MAIN_ID
			,	@SUB_ID
			,	1
		)

		SELECT CAST(SCOPE_IDENTITY() AS INT) [ID];
	END

	-- =================================
	-- DELETE OPTION
	-- =================================
	IF @FLAG = 'DELETE OPTION'
	BEGIN
		IF NOT EXISTS (SELECT 1 FROM [DOC].[Options] WHERE [ID] = @OPTION_ID AND [IS_ACTIVE] = 1)
		BEGIN
			RAISERROR('Option does not exist.', 16, 1);
			RETURN;
		END

		SELECT		@xOptionMainId	= [MAIN_CATEGORY_ID]
				,	@xOptionSubId	= [SUB_CATEGORY_ID]
		FROM		[DOC].[Options]
		WHERE		[ID] = @OPTION_ID

		/*
			A STRING ANSWER WITH NO OPTION LEFT IS UNANSWERABLE, THE SAME RULE
			THE FORMS ENFORCE WITH 'ADD AT LEAST ONE OPTION'.
		*/
		IF (
			SELECT	COUNT(1)
			FROM	[DOC].[Options]
			WHERE	[IS_ACTIVE] = 1
			AND		(
						(@xOptionMainId IS NOT NULL AND [MAIN_CATEGORY_ID] = @xOptionMainId)
					OR	(@xOptionSubId  IS NOT NULL AND [SUB_CATEGORY_ID]  = @xOptionSubId)
					)
		) <= 1
		BEGIN
			RAISERROR('Cannot remove the last option. Edit the category instead.', 16, 1);
			RETURN;
		END

		/*SOFT DELETE - THE LABEL STAYS AS HISTORY FOR DOCUMENTS THAT ALREADY USED IT*/
		UPDATE		[DOC].[Options]
		SET			[IS_ACTIVE] = 0
		WHERE		[ID] = @OPTION_ID
		AND			[IS_ACTIVE] = 1
	END

	-- =================================
	-- DELETE CATEGORY
	-- =================================
	IF @FLAG = 'DELETE CATEGORY'
	BEGIN
		/*
			SOFT DELETE. NOTHING IS REMOVED - THE CATEGORY AND ITS SUB CATEGORIES
			ARE FLAGGED INACTIVE, WHICH ALSO FREES THE NAME TO BE ADDED AGAIN.
		*/
		BEGIN TRY
			BEGIN TRANSACTION;

				UPDATE		[DOC].[SubCategory]
				SET			[IS_ACTIVE] = 0
				WHERE		[MAIN_ID] = @MAIN_ID
				AND			[IS_ACTIVE] = 1

				UPDATE		[DOC].[MainCategory]
				SET			[IS_ACTIVE] = 0
				WHERE		[ID] = @MAIN_ID
				AND			[IS_ACTIVE] = 1

			COMMIT TRANSACTION;
		END TRY
		BEGIN CATCH
			IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
			THROW;
		END CATCH
	END

END
