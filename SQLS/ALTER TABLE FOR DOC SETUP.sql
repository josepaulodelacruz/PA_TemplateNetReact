/*
	Adds CREATED_DATE / CREATED_BY / IS_ACTIVE to the DOC setup tables.
	Run this against databases that already have the tables from
	'CREATE TABLE FOR DOC SETUP.sql' - fresh installs already include the columns.

	Each column is added as NULL first so existing rows survive, backfilled,
	then tightened to NOT NULL. Re-running the script is safe.
*/

-- =================================
-- DOC.MainCategory
-- =================================
IF COL_LENGTH('DOC.MainCategory', 'CREATED_DATE') IS NULL
	ALTER TABLE DOC.[MainCategory] ADD [CREATED_DATE] DATETIME NULL CONSTRAINT [DF_MainCategory_CREATED_DATE] DEFAULT (GETDATE())
GO

IF COL_LENGTH('DOC.MainCategory', 'CREATED_BY') IS NULL
	ALTER TABLE DOC.[MainCategory] ADD [CREATED_BY] BIGINT NULL
GO

IF COL_LENGTH('DOC.MainCategory', 'IS_ACTIVE') IS NULL
	ALTER TABLE DOC.[MainCategory] ADD [IS_ACTIVE] BIT NULL CONSTRAINT [DF_MainCategory_IS_ACTIVE] DEFAULT (1)
GO

/*EXISTING ROWS PREDATE THE COLUMNS, SO THE DEFAULTS NEVER FIRED FOR THEM*/
UPDATE	DOC.[MainCategory]
SET		[CREATED_DATE] = GETDATE()
WHERE	[CREATED_DATE] IS NULL
GO

UPDATE	DOC.[MainCategory]
SET		[IS_ACTIVE] = 1
WHERE	[IS_ACTIVE] IS NULL
GO

ALTER TABLE DOC.[MainCategory] ALTER COLUMN [CREATED_DATE] DATETIME NOT NULL
GO

ALTER TABLE DOC.[MainCategory] ALTER COLUMN [IS_ACTIVE] BIT NOT NULL
GO

-- =================================
-- DOC.SubCategory
-- =================================
IF COL_LENGTH('DOC.SubCategory', 'CREATED_DATE') IS NULL
	ALTER TABLE DOC.[SubCategory] ADD [CREATED_DATE] DATETIME NULL CONSTRAINT [DF_SubCategory_CREATED_DATE] DEFAULT (GETDATE())
GO

IF COL_LENGTH('DOC.SubCategory', 'CREATED_BY') IS NULL
	ALTER TABLE DOC.[SubCategory] ADD [CREATED_BY] BIGINT NULL
