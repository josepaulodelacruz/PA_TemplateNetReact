IF COL_LENGTH('DOC.SubCategory', 'IS_ACTIVE') IS NULL
	ALTER TABLE DOC.[SubCategory] ADD [IS_ACTIVE] BIT NULL CONSTRAINT [DF_SubCategory_IS_ACTIVE] DEFAULT (1)
