ALTER TABLE DOC.[SubCategory] ALTER COLUMN [IS_ACTIVE] BIT NOT NULL
GO

-- =================================
-- DOC.Options
-- =================================
IF COL_LENGTH('DOC.Options', 'IS_ACTIVE') IS NULL
	ALTER TABLE DOC.[Options] ADD [IS_ACTIVE] BIT NULL CONSTRAINT [DF_Options_IS_ACTIVE] DEFAULT (1)
GO

UPDATE	DOC.[Options]
SET		[IS_ACTIVE] = 1
WHERE	[IS_ACTIVE] IS NULL
GO

ALTER TABLE DOC.[Options] ALTER COLUMN [IS_ACTIVE] BIT NOT NULL
GO

/*THE LOOKUPS ALWAYS FILTER ON IS_ACTIVE, AND MAIN_ID IS THE HOT JOIN COLUMN*/
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE [name] = 'IX_MainCategory_IS_ACTIVE' AND object_id = OBJECT_ID('DOC.MainCategory'))
	CREATE NONCLUSTERED INDEX [IX_MainCategory_IS_ACTIVE] ON DOC.[MainCategory] ([IS_ACTIVE]) INCLUDE ([NAME])
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE [name] = 'IX_SubCategory_MAIN_ID_IS_ACTIVE' AND object_id = OBJECT_ID('DOC.SubCategory'))
	CREATE NONCLUSTERED INDEX [IX_SubCategory_MAIN_ID_IS_ACTIVE] ON DOC.[SubCategory] ([MAIN_ID], [IS_ACTIVE])
GO

/*THE OPTIONS ARE ALWAYS READ THROUGH THEIR PARENT, EITHER THE MAIN OR THE SUB CATEGORY*/
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE [name] = 'IX_Options_MAIN_CATEGORY_ID_IS_ACTIVE' AND object_id = OBJECT_ID('DOC.Options'))
	CREATE NONCLUSTERED INDEX [IX_Options_MAIN_CATEGORY_ID_IS_ACTIVE] ON DOC.[Options] ([MAIN_CATEGORY_ID], [IS_ACTIVE])
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE [name] = 'IX_Options_SUB_CATEGORY_ID_IS_ACTIVE' AND object_id = OBJECT_ID('DOC.Options'))
	CREATE NONCLUSTERED INDEX [IX_Options_SUB_CATEGORY_ID_IS_ACTIVE] ON DOC.[Options] ([SUB_CATEGORY_ID], [IS_ACTIVE])
GO
