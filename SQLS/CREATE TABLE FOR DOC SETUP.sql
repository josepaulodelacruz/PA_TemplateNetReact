
CREATE TABLE DOC.[MainCategory] (
	ID INT IDENTITY(1,1) PRIMARY KEY
,	[NAME] VARCHAR(80)
,	[IS_NO_SUBCATEGORY] BIT NULL
,	[OPTION_TYPE] VARCHAR(80)
,	[CREATED_DATE] DATETIME NOT NULL DEFAULT (GETDATE())
,	[CREATED_BY] BIGINT NULL
,	[IS_ACTIVE] BIT NOT NULL DEFAULT (1)	/*0 = SOFT DELETED, THE NAME BECOMES FREE TO ADD AGAIN*/
)

CREATE TABLE DOC.[SubCategory] (
	[ID] INT IDENTITY(1,1) PRIMARY KEY
,	[NAME] VARCHAR(80)
,	[MAIN_ID] INT
,	[OPTION_TYPE] VARCHAR(80)
,	[CREATED_DATE] DATETIME NOT NULL DEFAULT (GETDATE())
,	[CREATED_BY] BIGINT NULL
,	[IS_ACTIVE] BIT NOT NULL DEFAULT (1)
)


CREATE TABLE DOC.[Options] (
	[ID] INT IDENTITY(1,1) PRIMARY KEY
,	[LABEL] VARCHAR(MAX)
,	[MAIN_CATEGORY_ID] INT NULL
,	[SUB_CATEGORY_ID] INT NULL
,	[IS_ACTIVE] BIT NOT NULL DEFAULT (1)	/*0 = SOFT DELETED, THE OPTION IS NO LONGER OFFERED*/
)


/*THE DOCUMENTS A BUYER HAS TO SUBMIT - WRITTEN BY [DOC].[NSP_ManageFileRequirements]*/
CREATE TABLE DOC.[FilesDocumentHDR] (
	[ID] INT IDENTITY(1,1) PRIMARY KEY
,	[TITLE] NVARCHAR(MAX) NULL
,	[LABEL_ID] INT NULL				/*[DOC].[Labels].[ID] - THE DOCUMENT TYPE*/
,	[IS_ACTIVE] BIT NULL DEFAULT (1)	/*0 = SOFT DELETED, THE TITLE BECOMES FREE TO ADD AGAIN*/
,	[CREATED_DATE] DATETIME NULL DEFAULT (GETDATE())
,	[CREATED_BY] VARCHAR(80) NULL	/*THE USERNAME, NOT THE USERS.ID*/
,	[UPDATED_DATE] DATETIME NULL
,	[UPDATED_BY] VARCHAR(80) NULL
)

CREATE TABLE [DOC].[Labels](
	[ID] [int] IDENTITY(1,1) NOT NULL,
	[LABEL] [varchar](120) NULL,
	[IS_ACTIVE] [bit] NULL,
	[CREATED_DATE] [datetime] NULL,
) 

